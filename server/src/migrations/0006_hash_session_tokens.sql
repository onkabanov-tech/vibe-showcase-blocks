-- Токены сессий теперь хранятся хешированными (SHA-256 — соль здесь не
-- нужна, в отличие от паролей: токен и так высокоэнтропийная случайная
-- строка из randomBytes(32), а не то, что мог выбрать человек). Если
-- файл БД когда-нибудь утечёт, из него нельзя будет напрямую подставить
-- значение в заголовок Authorization и выдать себя за вошедшего
-- пользователя — нужен исходный токен, а не то, что лежит в таблице.
--
-- Переименовываем колонку token -> token_hash, чтобы схема сама называла
-- вещи своими именами (см. server/src/sessions.js). SQLite обновляет
-- индекс на колонку автоматически при ALTER TABLE ... RENAME COLUMN —
-- пересоздаём его отдельно только чтобы переименовать сам индекс вслед
-- за колонкой, не ради работоспособности.
--
-- Существующие сессии при этом чистим: они хранят токен в открытом виде
-- и после перехода на хеш ни с чем не совпадут — по факту уже бесполезны
-- (следующий запрос с таким токеном и так получил бы 401), поэтому явно
-- удаляем их, а не оставляем висеть мёртвым грузом до истечения expires_at.
DELETE FROM sessions;

ALTER TABLE sessions RENAME COLUMN token TO token_hash;

DROP INDEX ux_sessions_token;
CREATE UNIQUE INDEX ux_sessions_token_hash ON sessions(token_hash);
